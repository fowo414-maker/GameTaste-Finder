// Generates en/js/games.js: an English copy of js/games.js.
// Only the `games` array and `gameDetails` object are translated (tags,
// mood, description, playTime, multiplayer, korean-support, ratings).
// Everything else (cover images, prices data, rawgData, formatGamePrice,
// isRecommendedGame) is carried over unchanged - it isn't language-specific,
// except formatGamePrice's two Korean strings which get patched below.
// Run with: node scripts/build-en-games.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const {
  translateList,
  translateMultiplayer,
  translatePlayTime,
  translateKoreanSupport,
  translateRatings,
  descriptionOverrides,
  phraseDict
} = require("./i18n-data.js");

const gamesJsPath = path.join(__dirname, "..", "js", "games.js");
const source = fs.readFileSync(gamesJsPath, "utf8");

const exportNames = [
  "games",
  "gameDetails",
  "duplicateGenreTags" // not actually exported by games.js; harmless if absent
];
const exportLine = `\n;(function(){ var __exports = {}; ${["games", "gameDetails"].map((n) => `__exports.${n} = ${n};`).join(" ")} return __exports; })()`;

const sandbox = {};
vm.createContext(sandbox);
const { games, gameDetails } = vm.runInContext(source + exportLine, sandbox);

const missing = new Set();

function translateGame(game) {
  const translated = { ...game };
  translated.tags = translateList(game.tags);
  translated.mood = translateList(game.mood);

  game.tags.concat(game.mood).forEach((word) => {
    if (!phraseDict[word]) missing.add(word);
  });

  translated.description = descriptionOverrides[game.id];
  if (!translated.description) missing.add(`[description:${game.id}]`);

  return translated;
}

const translatedGames = games.map(translateGame);

const translatedGameDetails = {};
Object.keys(gameDetails).forEach((id) => {
  const [releaseYear, playTime, difficulty, multiplayer, platforms, korean, ratings] = gameDetails[id];

  translatedGameDetails[id] = [
    releaseYear,
    translatePlayTime(playTime),
    difficulty,
    translateMultiplayer(multiplayer),
    platforms,
    translateKoreanSupport(korean),
    translateRatings(ratings)
  ];
});

if (missing.size > 0) {
  console.error("Missing translations for:", [...missing].join(", "));
  process.exit(1);
}

// Carry the rest of the original file (gameCoverUrls onward) through as-is,
// just patching formatGamePrice's two Korean strings.
const tailMarker = "const gameCoverUrls = {";
const tailIndex = source.indexOf(tailMarker);

if (tailIndex === -1) {
  throw new Error("Could not find gameCoverUrls in js/games.js - has the file structure changed?");
}

let tail = source.slice(tailIndex);
tail = tail.replace('return "가격 확인 필요";', 'return "Price TBD";');
tail = tail.replace('return "무료";', 'return "Free";');
tail = tail.replace('toLocaleString("ko-KR")', 'toLocaleString("en-US")');

const header = `// AUTO-GENERATED by scripts/build-en-games.js from js/games.js - do not edit by hand.\n// Re-run \`node scripts/build-en-games.js\` after js/games.js or scripts/i18n-data.js changes.\n`;

const output = `${header}
const games = ${JSON.stringify(translatedGames, null, 2)};

const gameDetails = ${JSON.stringify(translatedGameDetails, null, 2)};

${tail}`;

const outDir = path.join(__dirname, "..", "en", "js");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "games.js"), output);
console.log(`Wrote en/js/games.js (${translatedGames.length} games)`);
